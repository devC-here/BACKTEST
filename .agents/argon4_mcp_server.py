#!/usr/bin/env python3
"""
================================================================================
  ARGON 4 MCP SERVER BRIDGE (.agents/argon4_mcp_server.py)
================================================================================
FastMCP server bridge to consult Gemini 4 Argon via a logged-in Chrome browser
instance running with remote debugging enabled on port 9222.

Includes self-healing auto-launch of headless Chrome if port 9222 is not active,
automatic tab discovery/creation, authentication checks, sequential request
locking, and robust response extraction.
================================================================================
"""

import asyncio
import subprocess
import time
import urllib.request
import urllib.error
from fastmcp import FastMCP
from playwright.async_api import async_playwright

mcp = FastMCP("argon4-bridge")
call_lock = asyncio.Lock()


import socket

def check_chrome_status() -> bool:
    """Instantly checks whether Chrome remote debugging port 9222 is open."""
    try:
        with socket.create_connection(("127.0.0.1", 9222), timeout=0.3):
            return True
    except (socket.timeout, ConnectionRefusedError, OSError):
        return False


def ensure_chrome_debug() -> None:
    """
    Verifies Chrome remote debugging is active on port 9222.
    If not listening, spawns headless Chrome in the background with CREATE_NO_WINDOW
    and polls for up to 10 seconds until responsive.
    """
    if check_chrome_status():
        return

    chrome_path = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
    cmd = [
        chrome_path,
        "--remote-debugging-port=9222",
        r"--user-data-dir=C:\gemini_mcp_profile",
        "--no-first-run",
        "--no-default-browser-check",
        "https://gemini.google.com"
    ]
    creation_flags = 0x08000000 | 0x00000008  # CREATE_NO_WINDOW | DETACHED_PROCESS
    try:
        subprocess.Popen(cmd, creationflags=creation_flags, close_fds=True)
    except Exception as e:
        raise RuntimeError(f"Failed to spawn Chrome process: {e}")

    # Wait up to 10 seconds for the remote debugging endpoint to respond
    start_time = time.time()
    while time.time() - start_time < 10.0:
        if check_chrome_status():
            return
        time.sleep(0.5)

    if not check_chrome_status():
        raise RuntimeError(
            "Chrome failed to respond on http://127.0.0.1:9222/json/version within 10 seconds. "
            "Please check docs/ARGON4_MCP_BRIDGE.md for manual launch instructions."
        )


@mcp.tool()
async def ask_argon4(prompt: str, code_context: str = "") -> str:
    """
    Consults Gemini 4 Argon via an active, logged-in Chrome browser instance at http://127.0.0.1:9222.
    
    Args:
        prompt: The main user question or instruction for Gemini 4 Argon.
        code_context: Optional source code, logs, or data context to append to the prompt.
        
    Returns:
        The text response generated by Gemini 4 Argon.
    """
    async with call_lock:
        # Format combined prompt and code context
        full_message = prompt.strip()
        if code_context.strip():
            full_message = f"{full_message}\n\n```python\n{code_context.strip()}\n```"

        # Ensure Chrome is running with remote debugging enabled
        await asyncio.to_thread(ensure_chrome_debug)

        async with async_playwright() as p:
            # Connect over CDP to the Chrome instance without terminating it on disconnect
            browser = await p.chromium.connect_over_cdp("http://127.0.0.1:9222")
            try:
                target_page = None

                # Search all browser contexts and pages for an existing gemini.google.com tab
                for context in browser.contexts:
                    for page in context.pages:
                        if "gemini.google.com" in page.url:
                            target_page = page
                            break
                    if target_page:
                        break

                # If no tab exists with gemini.google.com, open one
                if not target_page:
                    context = browser.contexts[0] if browser.contexts else await browser.new_context()
                    target_page = await context.new_page()
                    await target_page.goto("https://gemini.google.com", wait_until="domcontentloaded")
                    await asyncio.sleep(2.0)

                # Check if redirected to Google sign-in
                if "accounts.google.com" in target_page.url:
                    return (
                        "Error: Google account is not authenticated in profile 'C:\\gemini_mcp_profile'. "
                        "Please run the visible Chrome login command in docs/ARGON4_MCP_BRIDGE.md to log into Google and select Gemini 4 Argon."
                    )

                # Bring tab to front
                await target_page.bring_to_front()

                # Locate prompt textbox
                textbox = target_page.locator('div[role="textbox"]').first
                try:
                    await textbox.wait_for(state="visible", timeout=15000)
                except Exception:
                    if "accounts.google.com" in target_page.url:
                        return (
                            "Error: Authentication required. Browser redirected to accounts.google.com. "
                            "Please run the visible Chrome login command in docs/ARGON4_MCP_BRIDGE.md to authenticate."
                        )
                    return (
                        "Error: Prompt textbox ('div[role=\"textbox\"]') not found on Gemini page. "
                        "Please check if Gemini is logged in or if the UI changed. See docs/ARGON4_MCP_BRIDGE.md."
                    )

                # Record initial model-response count to guarantee we only extract the newly generated answer
                response_elements = target_page.locator('model-response')
                initial_count = await response_elements.count()

                await textbox.click()
                await asyncio.sleep(0.3)

                # Clear any lingering text in textbox
                await target_page.keyboard.press("Control+A")
                await target_page.keyboard.press("Backspace")
                await asyncio.sleep(0.1)

                # Insert prompt text cleanly via CDP input into contenteditable editor
                await target_page.keyboard.insert_text(full_message)
                await asyncio.sleep(0.5)

                # Locate and trigger Send message button via native JS click to avoid Angular ripple overlay interception
                clicked = await target_page.evaluate('''() => {
                    const btn = document.querySelector('button[aria-label*="Send message" i], button[aria-label*="Submit" i]');
                    if (btn) {
                        btn.click();
                        return true;
                    }
                    return false;
                }''')
                if not clicked:
                    await target_page.keyboard.press("Enter")

                # Wait for the new model-response element to appear (up to 20s)
                start_wait = time.time()
                new_response_appeared = False
                while time.time() - start_wait < 20.0:
                    curr_count = await response_elements.count()
                    if curr_count > initial_count:
                        new_response_appeared = True
                        break
                    await asyncio.sleep(0.5)

                if not new_response_appeared:
                    return "Error: Prompt submitted, but no new model-response element appeared within 20 seconds."

                # Wait for generation to finish: monitor Stop button until hidden (up to 240s)
                stop_button = target_page.locator('button[aria-label*="Stop" i]')
                gen_start = time.time()
                while time.time() - gen_start < 240.0:
                    stop_vis = await stop_button.is_visible() if await stop_button.count() > 0 else False
                    if not stop_vis:
                        # 1.0s pause for DOM stabilization
                        await asyncio.sleep(1.0)
                        break
                    await asyncio.sleep(0.5)

                # Extract the newly generated model response
                last_element = response_elements.last
                text = await last_element.inner_text()
                # Clean up leading 'Gemini said\n' if present
                clean_text = text.strip()
                if clean_text.startswith("Gemini said"):
                    clean_text = clean_text[len("Gemini said"):].strip()
                return clean_text

            finally:
                # Detach from CDP session only; do NOT close the user's Chrome process
                await browser.close()


if __name__ == "__main__":
    mcp.run(transport="stdio", show_banner=False, log_level="ERROR")
